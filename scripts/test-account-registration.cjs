const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const tempRoot=fs.realpathSync(os.tmpdir());
const testDir=fs.mkdtempSync(path.join(tempRoot,'navand-account-test-'));
process.env.DATABASE_PATH=path.join(testDir,'test.sqlite');
process.env.LOG_DIR=path.join(testDir,'logs');
process.env.BACKUP_DIR=path.join(testDir,'backups');
process.env.BCRYPT_ROUNDS='4';
const appRoot=process.env.NAVAND_TEST_APP_ROOT || path.resolve(__dirname,'..');
const load=name=>import(pathToFileURL(path.resolve(appRoot,name)).href);
(async()=>{
  let database,server;
  try {
    database=await load('database/sqlite.js');
    const auth=await load('models/authModel.js');
    const accounts=await load('models/passwordRecoveryModel.js');
    database.initializeDatabase();
    const root=auth.loginUser({username:'root',password:'1234'});
    auth.updateUserCredentials({userId:root.id,currentPassword:'1234',username:'existing-owner',password:'original-owner'});
    let db=database.getDb();
    db.prepare("INSERT INTO app_settings (key,value) VALUES ('registration_data','keep-me')").run();
    const count=()=>database.getDb().prepare('SELECT COUNT(*) AS count FROM users').get().count;
    assert.equal(count(),1);
    assert.throws(()=>accounts.registerAccount({username:'invalid-code',password:'valid-password',recoveryCode:'123'}));
    assert.throws(()=>accounts.registerAccount({username:'x',password:'valid-password',recoveryCode:'12345678'}));
    assert.throws(()=>accounts.registerAccount({username:'short-pass',password:'123',recoveryCode:'12345678'}));
    assert.equal(count(),1);
    const user=accounts.registerAccount({username:' New-Account ',password:'chosen-password',recoveryCode:'۱۲۳۴۵۶۷۸'});
    assert.equal(user.username,'new-account');
    assert.equal(auth.loginUser({username:' NEW-ACCOUNT ',password:'chosen-password'}).id,user.id);
    assert.throws(()=>accounts.registerAccount({username:'NEW-ACCOUNT',password:'overwrite-password',recoveryCode:'87654321'}));
    assert.equal(auth.loginUser({username:'new-account',password:'chosen-password'}).id,user.id);
    assert.equal(count(),2);
    db.exec("CREATE TRIGGER reject_test_recovery BEFORE INSERT ON password_recovery WHEN (SELECT username FROM users WHERE id = NEW.user_id) = 'reject-test' BEGIN SELECT RAISE(ABORT, 'test rollback'); END");
    assert.throws(()=>accounts.registerAccount({username:'reject-test',password:'valid-password',recoveryCode:'12345678'}));
    assert.equal(count(),2);
    assert.equal(db.prepare("SELECT id FROM users WHERE username='reject-test'").get(),undefined);
    db.exec('DROP TRIGGER reject_test_recovery');
    database.closeDb();
    database.initializeDatabase();
    db=database.getDb();
    assert.equal(auth.loginUser({username:'new-account',password:'chosen-password'}).id,user.id);
    assert.equal(auth.loginUser({username:'existing-owner',password:'original-owner'}).id,root.id);
    assert.throws(()=>accounts.resetPassword({username:'existing-owner',password:'wrong-change',recoveryCode:'12345678'}));
    accounts.resetPassword({username:'new-account',password:'reset-password',recoveryCode:'١٢٣٤٥٦٧٨'});
    assert.throws(()=>auth.loginUser({username:'new-account',password:'chosen-password'}));
    assert.equal(auth.loginUser({username:'new-account',password:'reset-password'}).id,user.id);
    assert.throws(()=>accounts.resetPassword({username:'new-account',password:'another-password',recoveryCode:'12345678'}));
    assert.equal(db.prepare("SELECT value FROM app_settings WHERE key='registration_data'").get().value,'keep-me');
    const {createServer}=await load('services/serverService.js');
    server=createServer().listen(0,'127.0.0.1');
    await new Promise(resolve=>server.once('listening',resolve));
    const base='http://127.0.0.1:'+server.address().port;
    const post=(route,body)=>fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
    const input={username:'api-account',password:'api-password',recoveryCode:'87654321'};
    const created=await post('/api/auth/register',input);
    assert.equal(created.status,201);
    const result=await created.json();
    assert.equal(result.user.username,'api-account');
    assert.equal(result.recoveryCode,undefined);
    assert.equal((await post('/api/auth/register',input)).status,409);
    assert.equal((await post('/api/auth/login',{username:input.username,password:input.password})).status,200);
    assert.equal((await post('/api/auth/reset-password',{username:input.username,recoveryCode:input.recoveryCode,password:'new-api-password'})).status,200);
    assert.equal((await post('/api/auth/login',{username:input.username,password:'new-api-password'})).status,200);
    console.log('Account registration passed: atomic account and code creation, validation, duplicates, persistence, old accounts and data, per-account recovery, login, HTTP endpoints.');
  } finally {
    if(server) await new Promise(resolve=>server.close(resolve));
    if(database) database.closeDb();
    const resolved=fs.realpathSync(testDir);
    if(path.dirname(resolved)!==tempRoot || !path.basename(resolved).startsWith('navand-account-test-')) throw new Error('Unsafe cleanup path');
    fs.rmSync(resolved,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
